export function applyDnd2014Rulebook(profile) {
    const defaults = {};

    for (const chapter of BOOK_DESIGN_CHAPTERS) {
        const fields = DESCRIPTIONS[chapter.code];

        if (!fields) continue;

        defaults[chapter.code] = {
            label: chapter.title,
            status: chapter.code === 'networks' ? 'unused' : 'described',
            fields: {...fields}
        };
    }

    profile.rulebook = {...defaults, ...(profile.rulebook ?? {})};

    return profile;
}